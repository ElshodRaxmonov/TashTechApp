enum class ThemeMode { System, Light, Dark }

/** Semantic colors that have no Material 3 slot. */
@Immutable
data class ExtendedColors(
    val success: Color,
    val warning: Color,
    val info: Color,
)
fun ThemeMode.toNightMode(): Int = when (this) {
    ThemeMode.System -> AppCompatDelegate.MODE_NIGHT_FOLLOW_SYSTEM
    ThemeMode.Light -> AppCompatDelegate.MODE_NIGHT_NO
    ThemeMode.Dark -> AppCompatDelegate.MODE_NIGHT_YES
}

private val LightExtendedColors = ExtendedColors(LightSuccess, LightWarning, LightInfo)
private val DarkExtendedColors = ExtendedColors(DarkSuccess, DarkWarning, DarkInfo)

val LocalExtendedColors = staticCompositionLocalOf { LightExtendedColors }

val MaterialTheme.extended: ExtendedColors
    @Composable @ReadOnlyComposable get() = LocalExtendedColors.current

